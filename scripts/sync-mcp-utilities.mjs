import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const source = new URL('apps/desktop/src/features/utilities/shared/core.ts', root);
const destination = new URL('packages/mcp/src/utility-core.ts', root);
const expected = '// Generated by scripts/sync-mcp-utilities.mjs; edit the desktop shared core.\n' + await readFile(source, 'utf8');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== expected) throw new Error('MCP utility core is stale. Run the sync script.');
} else { await writeFile(destination, expected); }
console.log(`MCP utilities ${process.argv.includes('--check') ? 'verified' : 'synced'}: ${fileURLToPath(destination)}`);
